//! Memory query use case.
//!
//! ADR-040: wraps Grafeo memory operations behind a trait so the HTTP
//! server does not directly depend on the memory store type.
//!
//! The types exposed here are the **single source of truth** for the
//! memory-query wire format (HTTP JSON shape documented in
//! `docs/zh/protocols/http.md` §7.7 + the canonical `MemoryStatsResponse`
//! shape mirrored in `acowork-gateway::http::memory_api`). They are
//! `Serialize`/`Deserialize` so the HTTP handlers can ferry them
//! through `serde_json::to_value` directly — no separate JSON-shaping
//! layer that could drift from the public contract.

use std::collections::HashMap;
use std::sync::Arc;

use async_trait::async_trait;
use serde::{Deserialize, Serialize};

use crate::error::Result;

/// Parameters for listing memory nodes (paginated, filtered).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryNodeQuery {
    pub page: u32,
    pub size: u32,
    pub node_type: String,
    /// Sub-classification filter (Knowledge / Autobiographical only).
    /// See [`crate::http::memory_query::ListNodesParams::sub_type`].
    #[serde(default)]
    pub sub_type: String,
    pub keyword: String,
    pub time_range: String,
}

/// Semantic search over memory nodes (ADR-081 P1-1).
///
/// `mode` ∈ `{"vector", "hybrid", "keyword"}`. `embedding` is generated by
/// the HTTP layer (from the agent's live embedding provider) and passed
/// through; when it is `None` the engine falls back to BM25 text search.
#[derive(Debug, Clone, Default)]
pub struct SemanticMemoryQuery {
    /// Query text as written. This is what gets embedded for the vector source.
    pub query_text: String,
    pub mode: String,
    pub limit: usize,
    pub embedding: Option<Vec<f32>>,
    /// Pre-analyzed terms driving the lexical source (ADR-095 D2).
    ///
    /// Empty means "no analyzer output" and falls back to `query_text` inside
    /// the engine — an analyzer miss must never cost recall. Kept on the query
    /// rather than a side parameter so the dual query travels as one unit and
    /// cannot be paired with the wrong raw text at a call site.
    pub lexical_terms: Vec<String>,
}

/// Lightweight memory node for list responses.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryNode {
    pub node_id: u64,
    pub node_type: String,
    /// Secondary classification (see [`AdminNodeRecord::sub_type`]).
    /// `None` for Episodic/Procedural nodes.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub sub_type: Option<String>,
    pub content: String,
    pub confidence: f64,
    /// Raw `importance` property on the node (0.0 when the node type has no
    /// such property — e.g. Procedural/Autobiographical). Passed through
    /// verbatim, never derived.
    pub importance: f64,
    pub decay_score: f64,
    pub created_at: i64,
    pub last_accessed_at: i64,
    pub access_count: u32,
    pub status: String,
}

/// Response for listing memory nodes.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryNodeListResponse {
    pub nodes: Vec<MemoryNode>,
    pub total: u64,
    pub page: u32,
    pub size: u32,
    pub model_dim: u64,
}

/// A memory node plus how the retrieval engine matched it (ADR-095 D4).
///
/// `evidence` is `None` when the answering provider cannot report per-source
/// signals — deliberately nullable here even though the engine-level
/// [`acowork_core::retrieval::FusedHit`] always knows, because the honest
/// statement for "did not compute" is absence, not a guess.
#[derive(Debug, Clone)]
pub struct ScoredMemoryNode {
    pub node: MemoryNode,
    pub evidence: Option<RetrievalEvidence>,
}

/// Per-source retrieval signals for one hit.
///
/// Ranks are **in-source** (position inside each candidate pool), not
/// comparable across sources; `fused_score` is the in-source RRF signal and
/// must not be presented as a similarity.
#[derive(Debug, Clone)]
pub struct RetrievalEvidence {
    pub matched_by: acowork_core::retrieval::MatchedBy,
    pub vector_rank: Option<usize>,
    pub text_rank: Option<usize>,
    pub cosine: Option<f64>,
    pub fused_score: f64,
    /// `None` when the answering source has no fusion to rank (the legacy
    /// single-path search).
    pub fused_rank: Option<usize>,
}

impl RetrievalEvidence {
    /// The **whitelisted** client-facing projection of these signals.
    ///
    /// Lives on the type rather than at each call site on purpose: `cosine` and
    /// `fused_score` must not reach the list payload (design 28 §4.2 — a cosine
    /// in a UI payload gets rendered as a confidence percentage, and this one
    /// is not calibrated). Putting the projection here means adding a field to
    /// the struct does not silently publish it to Desktop.
    ///
    /// Absent signals are omitted, not emitted as `null`: a consumer reading
    /// `matched_by` then sees "unknown" instead of inventing a category.
    pub fn to_payload(&self) -> serde_json::Value {
        let mut map = serde_json::Map::new();
        self.write_into(&mut map);
        serde_json::Value::Object(map)
    }

    /// Merge the evidence keys into an existing scope payload.
    ///
    /// Evidence is **additive**: a hit is only actionable if the UI keeps its
    /// locate keys (`node_id`, `session_id`, ...). Building the evidence object
    /// and assigning it as the whole payload silently drops those, which is why
    /// this helper exists and why every scope uses it.
    pub fn merge_into(&self, payload: &mut serde_json::Map<String, serde_json::Value>) {
        self.write_into(payload);
    }

    fn write_into(&self, map: &mut serde_json::Map<String, serde_json::Value>) {
        map.insert(
            "matched_by".to_string(),
            serde_json::json!(self.matched_by),
        );
        if let Some(r) = self.vector_rank {
            map.insert("vector_rank".to_string(), serde_json::json!(r));
        }
        if let Some(r) = self.text_rank {
            map.insert("text_rank".to_string(), serde_json::json!(r));
        }
        if let Some(r) = self.fused_rank {
            map.insert("fused_rank".to_string(), serde_json::json!(r));
        }
    }
}

/// Memory store statistics.
///
/// This struct is the single source of truth for the `GET /memory/stats`
/// wire format. The HTTP handler serializes it directly with
/// `serde_json::to_value`; the service-layer trait returns it directly;
/// the internal `http::memory_query::get_stats` business logic also
/// returns it (so the pre-ADR-040 fallback path produces byte-identical
/// JSON to the ADR-040 service path). Field names + types mirror the
/// canonical `MemoryStatsResponse` defined in
/// `acowork-gateway::http::memory_api`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryStats {
    /// Total number of memory nodes across all labels.
    pub total_nodes: u64,
    /// On-disk storage size in bytes. Reserved for future use; currently 0.
    pub storage_bytes: u64,
    /// Node count grouped by memory label (`Knowledge` / `Episodic` / etc.).
    pub by_type: HashMap<String, u64>,
    /// Node count grouped by status (`Active` / `Dormant` / `purged`).
    /// The desktop Memory panel reads `by_status["Active"]` /
    /// `by_status["Dormant"]` to drive its status cards.
    pub by_status: HashMap<String, u64>,
    /// Vector-index health string (`healthy` / `no_store` / `error: …`).
    pub index_health: String,
    /// Embedding dimension of the persisted HNSW index. 0 if no index.
    /// Compared against `model_dim` by the desktop to detect dimension
    /// mismatches and surface the "Rebuild Index" banner.
    pub stored_dim: u64,
    /// Number of nodes with a non-NULL `embedding` field. Compared against
    /// `total_nodes` to detect missing embeddings.
    pub nodes_with_embedding: u64,
    /// Vectors stored at a width other than `stored_dim`, and therefore
    /// invisible to vector search. Mirrored from
    /// `acowork_memory::admin::AdminStats::vectors_of_other_dim`; the desktop
    /// Memory panel shows its "Rebuild Index" banner on this being non-zero.
    pub vectors_of_other_dim: u64,
    /// Rows a rebuild with `scope = "all"` would re-embed (every row in the
    /// migration label set, conversation index included). The desktop panel
    /// shows this on the banner so the promised row count equals the
    /// progress bar's total; 0 on engines that cannot pre-count.
    pub rebuild_rows_all: u64,
    /// Rows a rebuild with `scope = "repair"` would re-embed against
    /// `model_dim` - vectors of a foreign width plus rows with no vector at
    /// all, over the migration label set. This is the exact number the
    /// repair rebuild's progress total will report, so the banner cannot
    /// promise one count and process another.
    pub rebuild_rows_repair: u64,
    /// Embedding dimension of the active embedding model (0 if none).
    pub model_dim: u64,
    /// On-disk schema version of the underlying store (`PRAGMA user_version`
    /// for SQLite; 0 when the engine has no equivalent knob).
    pub schema_version: u64,
}

/// Result of an embedding-dimension rebuild.
///
/// Mirrors `MemoryAdminService::migrate_embedding_dimension`'s
/// `RebuildStats` so the HTTP handler can ferry it through
/// `serde_json::to_value` without engine-specific types.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct RebuildReport {
    /// Total nodes scanned.
    pub total_scanned: u64,
    /// Nodes successfully re-embedded.
    pub rebuilt: u64,
    /// Nodes skipped because they had no embedding vector.
    pub skipped_no_embedding: u64,
    /// Nodes skipped because they had no content.
    pub skipped_no_content: u64,
    /// Nodes that failed during re-embedding.
    pub errors: u64,
    /// Human-readable summary message for the UI.
    pub message: String,
}

/// Memory query methods.
#[async_trait]
pub trait MemoryQueryService: Send + Sync {
    /// List nodes with pagination, type/keyword/time-range filters.
    async fn list_nodes(&self, query: &MemoryNodeQuery) -> Result<MemoryNodeListResponse>;

    /// Semantic (vector/hybrid/keyword) search over memory nodes
    /// (ADR-081 P1-1). When `query.embedding` is `None`, `semantic_search`
    /// falls back to BM25 text search regardless of `query.mode`.
    async fn semantic_search(
        &self,
        query: &SemanticMemoryQuery,
    ) -> Result<MemoryNodeListResponse>;

    /// Semantic search that keeps the retrieval evidence with each hit
    /// (ADR-095 D4). Global search uses this to choose summary candidates,
    /// which are selected from `matched_by` and in-source rank rather than
    /// from the fused score alone.
    ///
    /// `lexical_terms` drives the FTS source and is deliberately separate from
    /// the embedded `query.query_text` (D2); an empty list falls back to the
    /// raw text inside the engine.
    ///
    /// The default implementation projects [`Self::semantic_search`] and
    /// reports **no** evidence (`evidence: None`) rather than guessing one: a
    /// provider without a hybrid engine must not claim it fused two sources.
    /// Callers that require signals should treat `None` as "this source cannot
    /// tell me how it matched".
    async fn semantic_search_detailed(
        &self,
        query: &SemanticMemoryQuery,
        policy: &acowork_core::retrieval::FusionPolicy,
    ) -> Result<Vec<ScoredMemoryNode>> {
        let _ = policy;
        let resp = self.semantic_search(query).await?;
        Ok(resp
            .nodes
            .into_iter()
            .map(|node| ScoredMemoryNode { node, evidence: None })
            .collect())
    }

    /// Get a single node by id.
    async fn get_node(&self, node_id: u64) -> Result<serde_json::Value>;

    /// Get memory store statistics.
    async fn get_stats(&self) -> Result<MemoryStats>;

    /// Re-embed nodes with a new embedding function/dimension, reporting
    /// progress, limited to the rows named by `scope`.
    ///
    /// `endpoint` / `model_id` / `dimension` describe the new embedding
    /// model the Gateway has switched to. The implementation builds a
    /// temporary provider and migrates the stored vectors, rebuilding the
    /// HNSW indexes (Bug3: restores the dimension-migration feature that
    /// was lost in the gRPC→MQTT refactor).
    ///
    /// `scope` separates the two reasons a rebuild is asked for: `All`
    /// for a model swap (every vector changes meaning), `Repair` for a
    /// store whose declared dimension already matches the model but holds
    /// a few foreign-width or unembedded rows (only those are invisible
    /// to retrieval, and only those are re-embedded).
    ///
    /// `progress` is called with `(processed, total)` after each node is
    /// re-embedded. The HTTP layer uses this to power a long-running
    /// rebuild as a background task plus a `GET /memory/rebuild-progress`
    /// polling endpoint, so a large store never trips a client/proxy
    /// timeout and the UI can show `rebuilt/total`.
    async fn rebuild_embeddings_with_progress(
        &self,
        endpoint: &str,
        model_id: &str,
        dimension: usize,
        scope: acowork_memory::admin::RebuildScope,
        progress: Option<Arc<dyn Fn(u64, u64) + Send + Sync>>,
    ) -> Result<RebuildReport>;

    /// Delete a node by id.
    async fn delete_node(&self, node_id: u64) -> Result<()>;

    /// Create a new memory node.
    ///
    /// `input.label` is the node label (e.g. `"Knowledge"`, `"Episodic"`).
    /// `input.properties` is a flat key→JSON map; the implementation is
    /// responsible for serialising values into the underlying store. Returns
    /// the newly-assigned `node_id`.
    async fn create_node(&self, input: &CreateMemoryNodeInput) -> Result<u64>;

    /// Update (merge) properties on an existing node.
    ///
    /// Existing properties not listed in `properties` are left untouched.
    /// Returns 404 (mapped from a dedicated error) if the node is absent.
    async fn update_node(
        &self,
        node_id: u64,
        properties: &HashMap<String, serde_json::Value>,
    ) -> Result<()>;
}

/// Input for [`MemoryQueryService::create_node`].
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CreateMemoryNodeInput {
    /// Node label (e.g. `"Knowledge"`, `"Episodic"`).
    pub label: String,
    /// Flat key→JSON property map. Empty map is allowed.
    pub properties: HashMap<String, serde_json::Value>,
}

#[cfg(test)]
mod retrieval_evidence_tests {
    use super::*;
    use acowork_core::retrieval::MatchedBy;

    fn evidence() -> RetrievalEvidence {
        RetrievalEvidence {
            matched_by: MatchedBy::Both,
            vector_rank: Some(1),
            text_rank: Some(0),
            cosine: Some(0.72),
            fused_score: 0.032,
            fused_rank: Some(0),
        }
    }

    /// The payload is locate keys *plus* evidence, never evidence *instead of*
    /// locate keys. Dropping `node_id` made every memory preview fetch node 0
    /// and spin forever, so this is a regression guard, not a shape preference.
    #[test]
    fn merge_into_adds_evidence_without_touching_locate_keys() {
        let mut payload = serde_json::Map::new();
        payload.insert("node_id".to_string(), serde_json::json!(42u64));
        payload.insert("node_type".to_string(), serde_json::json!("Knowledge"));
        payload.insert("sub_type".to_string(), serde_json::json!(null));

        evidence().merge_into(&mut payload);

        assert_eq!(payload.get("node_id").and_then(|v| v.as_u64()), Some(42));
        assert_eq!(payload.get("node_type").and_then(|v| v.as_str()), Some("Knowledge"));
        assert!(payload.contains_key("sub_type"), "sub_type must survive, even as null");
        assert_eq!(payload.get("matched_by").and_then(|v| v.as_str()), Some("both"));
        assert_eq!(payload.get("fused_rank").and_then(|v| v.as_u64()), Some(0));
    }

    /// Cosine stays out of the merged payload for the same reason it stays out
    /// of `to_payload`: an uncalibrated similarity must not reach the UI.
    #[test]
    fn merge_into_does_not_expose_cosine() {
        let mut payload = serde_json::Map::new();
        payload.insert("node_id".to_string(), serde_json::json!(7u64));
        evidence().merge_into(&mut payload);
        assert!(
            !payload.contains_key("cosine"),
            "cosine must not be published to the list payload"
        );
    }
}
