#[cfg(test)]
mod tests {
    use super::*;

    fn temp_vault_dir(name: &str) -> String {
        let dir = std::env::temp_dir().join(format!("acowork-test-state-{name}"));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir.to_string_lossy().to_string()
    }

    #[test]
    fn test_state_new() {
        let dir = temp_vault_dir("new");
        let state = GatewayState::new(&dir);
        assert!(state.installed_agents.is_empty());
        assert!(state.running_agents.is_empty());
        assert!(!state.vault.is_unlocked());
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// `started_at` backs `GET /api/status`'s `uptime_secs`, which the
    /// Desktop's service-diagnostics panel renders. It used to be a
    /// hardcoded `0` ("TODO: track actual uptime"), so pin that
    /// construction stamps a real time — and that uptime derived from it
    /// is non-negative and small.
    #[test]
    fn test_state_new_stamps_started_at() {
        let dir = temp_vault_dir("started-at");
        let before = Utc::now();
        let state = GatewayState::new(&dir);
        let after = Utc::now();

        assert!(
            state.started_at >= before && state.started_at <= after,
            "started_at must be the construction time, got {}",
            state.started_at
        );
        let uptime = (Utc::now() - state.started_at).num_seconds();
        assert!(
            (0..5).contains(&uptime),
            "a freshly constructed state must report a near-zero uptime, got {uptime}s"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_state_install_and_check() {
        let dir = temp_vault_dir("install");
        let mut state = GatewayState::new(&dir);
        assert!(!state.is_installed("com.example.weather"));

        let toml_str = r#"
            agent_id = "com.example.weather"
            version = "1.0.0"
            name = "Weather Agent"
            description = "Weather queries"
            author = "test"
            runtime_version = "0.1.0"
            [llm]
            provider = "openai"
            model = "gpt-4"
        "#;
        let manifest = acowork_core::AgentManifest::from_toml(toml_str).unwrap();

        state.add_installed(AgentInfo {
            instance_id: "1f0c9a5e-7d2b-4c6a-8e31-0b6c5d4e3f21".to_string(),
            agent_id: "com.example.weather".to_string(),
            version: "1.0.0".to_string(),
            name: "Weather Agent".to_string(),
            install_path: "/tmp/weather".to_string(),
            manifest,
            node_id: "local".to_string(),
        });
        // ADR-073: the install table is keyed by INSTANCE identity. The
        // package id is metadata on the row, never a lookup key — a
        // package may have several instances, so resolving it to "an"
        // entry would be ambiguous.
        assert!(state.is_installed("1f0c9a5e-7d2b-4c6a-8e31-0b6c5d4e3f21"));
        assert!(!state.is_installed("com.example.weather"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_state_running() {
        let dir = temp_vault_dir("running");
        let mut state = GatewayState::new(&dir);
        state.add_running(RunningAgentInfo {
            instance_id: "1f0c9a5e-7d2b-4c6a-8e31-0b6c5d4e3f21".to_string(),
            agent_id: "com.example.weather".to_string(),
            pid: 1234,
            started_at: chrono::Utc::now(),
            workspace: "/tmp/weather-workspace".to_string(),
            node_id: "local".to_string(),
            lifecycle: acowork_core::mqtt_proto::AgentLifecycleState::Offline,
            lifecycle_detail: String::new(),
            dev_mode: false,
            debug_state: DebugState::Disabled,
            debug_port: None,
            workspace_config_json: None,
            current_embed_dim: None,
            migration: None,
        });
        // ADR-073: keyed by instance identity, exactly like the install table.
        assert!(state.is_running("1f0c9a5e-7d2b-4c6a-8e31-0b6c5d4e3f21"));
        assert!(!state.is_running("com.example.weather"));

        state.remove_running("1f0c9a5e-7d2b-4c6a-8e31-0b6c5d4e3f21");
        assert!(!state.is_running("1f0c9a5e-7d2b-4c6a-8e31-0b6c5d4e3f21"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_instance_id_default_is_empty() {
        let dir = temp_vault_dir("instance-id-default");
        let state = GatewayState::new(&dir);
        assert!(state.instance_id.is_empty());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_set_instance_id_assigns() {
        let dir = temp_vault_dir("instance-id-set");
        let mut state = GatewayState::new(&dir);
        state.set_instance_id("instance-A".to_string());
        assert_eq!(state.instance_id, "instance-A");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_set_instance_id_is_idempotent() {
        let dir = temp_vault_dir("instance-id-idempotent");
        let mut state = GatewayState::new(&dir);
        state.set_instance_id("instance-A".to_string());
        // Second call must NOT overwrite — mutating the id mid-run
        // would invalidate every already-published snapshot's
        // instance_id.
        state.set_instance_id("instance-B".to_string());
        assert_eq!(state.instance_id, "instance-A");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_touch_and_get_interaction_round_trip() {
        // ADR-073: key is the agent `instance_id` (install-time UUID),
        // not the package `agent_id`. Two instances of the same package
        // must keep independent timestamps.
        let dir = temp_vault_dir("touch-interaction");
        let mut state = GatewayState::new(&dir);

        let when_a = Utc::now();
        let when_b = when_a + chrono::Duration::seconds(60);
        state.touch_interaction("inst-aaaa-1111", when_a);
        state.touch_interaction("inst-bbbb-2222", when_b);

        assert_eq!(state.get_interaction("inst-aaaa-1111"), Some(when_a));
        assert_eq!(state.get_interaction("inst-bbbb-2222"), Some(when_b));
        // Lookup by package id (the legacy wrong key) must miss.
        assert_eq!(state.get_interaction("com.acowork.foo"), None);
        let _ = std::fs::remove_dir_all(&dir);
    }
}
