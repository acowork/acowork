//! MemoryProvider trait - standardized interface for memory storage backends.
//!
//! The single storage abstraction of the memory layer (ADR-101 retired the old
//! `MemoryStore` trait, which had no implementation left). Its methods cover
//! everything a memory engine has to offer the service:
//! - Hybrid retrieval (vector + full-text)
//! - Memory store tool entry (conflict detection, dedup, node creation)
//! - Ambiguous conflict confirmation
//! - Experience generalization (Path C)
//! - Node CRUD (procedural, autobiographical, edges)
//! - Consolidation lifecycle (start, stop, notify, run offline)
//!
//! Implementation: [`crate::sqlite::SqliteStore`] (ADR-082), one database per
//! agent instance.
//!
//! Design ref: ADR-051, ADR-082, ADR-101

use std::time::Duration;

use acowork_core::error::Result;
use async_trait::async_trait;
use chrono::{DateTime, Utc};

use crate::quality::MemoryQualityConfig;
use crate::types::{
    AutobioCategory, AutobiographicalNode, CollaborationSpan, DecayScanResult,
    Episode, EpisodicDecayConfig, KnowledgeNode, KnowledgeSubType, MemoryQuery, NodeStatus,
    ProceduralNode, SearchResult, StoreHealth, StoreStats,
};

/// MemoryProvider trait - standardized interface for memory storage backends.
///
/// This is the abstraction layer between the memory service and the storage
/// engine. The service holds a `dyn MemoryProvider` and never touches the
/// concrete engine directly.
///
/// Implementations: [`crate::sqlite::SqliteStore`] (ADR-082) and the test
/// doubles in this crate.
///
/// Design ref: ADR-051, ADR-082, ADR-101
#[async_trait]
pub trait MemoryProvider: Send + Sync {
    // ── Episodic layer ───────────────────────────────────────────────────

    /// Store an interaction episode.
    ///
    /// Episode content is stored as-is.
    /// Embedding is generated by Runtime and passed in.
    ///
    /// Returns the storage id of the stored episode (allocated by the
    /// provider). ADR-068 A4: distiller audits map evaluations back to real
    /// nodes, so the id must not be discarded at this boundary.
    fn store_episode(&self, episode: &Episode) -> Result<u64>;

    /// Search episodic memories by query.
    fn search_episodes(&self, query: &MemoryQuery) -> Result<Vec<SearchResult>>;

    /// Mark episodes as consolidated.
    fn mark_consolidated(&self, ids: &[u64]) -> Result<()>;

    /// Exact cosine top-`k` scan over one label's stored vectors.
    ///
    /// Used by the distiller's merge step to recall the existing semantic
    /// nodes most similar to one new statement. Deliberately *not*
    /// [`Self::hybrid_search`]: that pipeline applies abstention, decay and
    /// token-budget logic meant for answering a user, all of which would
    /// distort a dedup recall. Returns `(node_id, cosine)` pairs, best first.
    fn vector_search(&self, label: &str, query: &[f32], k: usize) -> Result<Vec<(u64, f64)>>;

    /// Cleanup consolidated episodes older than the given duration.
    fn cleanup_episodes(&self, older_than: Duration) -> Result<u64>;

    /// Retrieve episodes for conversation history.
    ///
    /// If `session_id` is provided, returns episodes for that session ordered by
    /// timestamp descending. Otherwise returns all episodes across all sessions.
    fn get_episodes(&self, session_id: Option<&str>, limit: usize) -> Result<Vec<Episode>>;

    /// Retrieve unconsolidated episodes for offline distillation (ADR-068).
    ///
    /// Returns only episodes with `consolidated == false`, optionally filtered
    /// by `knowledge_subtype`. Each entry carries the episode's storage node id
    /// (`u64`) alongside the [`Episode`] — the id is required by callers to
    /// mark episodes consolidated after promotion and to record
    /// `source_episode_ids` on promoted nodes.
    ///
    /// Ordered by timestamp descending (newest first).
    ///
    /// The window used to be oldest-first, which starved permanently: a run
    /// reads at most `limit` rows, so an episode that repeatedly failed (and
    /// was therefore left unconsolidated for retry) sat at the head of every
    /// subsequent window and blocked everything behind it. Newest-first makes
    /// the freshest memories consolidate first and lets a stuck episode drift
    /// to the tail instead of holding the queue.
    fn get_episodes_by_subtype(
        &self,
        subtype: Option<KnowledgeSubType>,
        limit: usize,
    ) -> Result<Vec<(u64, Episode)>>;

    /// Count unconsolidated episodes (ADR-071 D1).
    ///
    /// This is the EpisodicDistiller's candidate backlog and drives the
    /// background scheduler's distiller trigger — decoupled from the legacy
    /// `Pending` sediment-node count, which has had no producer since
    /// ADR-068 and therefore can no longer gate the distiller.
    ///
    /// Must use the same predicate as
    /// [`get_episodes_by_subtype`](Self::get_episodes_by_subtype), or the
    /// scheduler's backlog number and the distiller's actual work queue drift
    /// apart and the status panel reports a queue that no run will ever drain.
    fn count_unconsolidated_episodes(&self) -> Result<usize>;

    /// Collaboration span across all episodes (ADR-068 M8).
    ///
    /// Returns the earliest stored episode timestamp and the total episode
    /// count. `None` when the store has no episodes. Consumed by the
    /// 30-day Relationship auto-generation in the EpisodicDistiller so the
    /// Relationship category has exactly one producer (the distiller) with a
    /// full audit trail.
    fn collaboration_span(&self) -> Result<Option<CollaborationSpan>>;

    // ── Semantic layer ───────────────────────────────────────────────────

    /// Store or update a knowledge node (Fact/Preference/Relation).
    ///
    /// Fact nodes are automatically deduplicated by (subject, predicate).
    /// Returns the storage id of the written node — the id of the existing
    /// node when the write was a dedup merge, otherwise the fresh id.
    fn store_knowledge(&self, node: &KnowledgeNode) -> Result<u64>;

    /// Load a knowledge node by id.
    fn get_knowledge(&self, id: u64) -> Result<Option<KnowledgeNode>>;

    /// Overwrite an existing knowledge node.
    ///
    /// [`KnowledgeNode`] carries no id, so the target is explicit. Used by the
    /// distiller's merge step, which must update a node in place rather than
    /// insert a near-duplicate.
    fn update_knowledge(&self, id: u64, node: &KnowledgeNode) -> Result<()>;

    /// Store or update a procedural memory node.
    /// Returns the storage id of the written node.
    fn store_procedural(&self, node: &ProceduralNode) -> Result<u64>;

    /// Store or update an autobiographical memory node.
    ///
    /// Status is forced to Active (enforced by schema).
    /// Returns the storage id of the written node.
    fn store_autobiographical(&self, node: &AutobiographicalNode) -> Result<u64>;

    // ── Unified retrieval ───────────────────────────────────────────────

    /// Hybrid search: vector + full-text + RRF fusion.
    ///
    /// Searches across all labels (Episodic/Knowledge/Procedural/Autobiographical).
    fn hybrid_search(&self, query: &MemoryQuery) -> Result<Vec<SearchResult>>;

    // ── Forgetting ───────────────────────────────────────────────────────


    /// Run episodic forgetting (pure time decay) with the given config.
    ///
    /// Only touches `Episodic` nodes (the沉淀层 is intentionally excluded).
    /// When `config.enabled` is false this is a no-op returning zeroes.
    ///
    /// Progressive semantics (no age cliff):
    /// - `retention = exp(-ln2 * age_days / half_life_days)`
    /// - Active nodes with `retention < dormant_threshold` → Dormant.
    /// - Dormant nodes dormant for `archive_days` → archived to the
    ///   PurgeLog (30-day recovery window).
    fn run_episodic_decay_scan(&self, config: &EpisodicDecayConfig) -> Result<DecayScanResult>;



    // ── Lifecycle ───────────────────────────────────────────────────────

    /// Health check for monitoring and diagnostics.
    fn health_check(&self) -> Result<StoreHealth>;

    /// Storage statistics (node counts, storage size, index status).
    fn stats(&self) -> Result<StoreStats>;

    /// Close the store, flushing pending writes.
    fn close(&self) -> Result<()>;

    // ── Phase 1: Hybrid retrieval (extended) ────────────────────────────

    /// Run hybrid retrieval (vector + full-text), returning (node_id, score) pairs.
    ///
    /// `#[allow(clippy::too_many_arguments)]`: this is a thin trait-method
    /// signature whose parameters (query, embedding, weights, filter) are
    /// semantically independent retrieval inputs; bundling them into a
    /// struct would obscure the call sites without reducing real complexity.
    #[allow(clippy::too_many_arguments)]
    fn hybrid_search_full(
        &self,
        label: &str,
        query_text: &str,
        embedding: &[f32],
        k: usize,
        text_weight: f64,
        vector_weight: f64,
        min_cosine: Option<f32>,
    ) -> Result<Vec<(u64, f64)>>;

    /// Hybrid retrieval that keeps the per-source signals ADR-095 D4 requires
    /// (`matched_by`, in-source rank, cosine, fused rank).
    ///
    /// `lexical_query` drives the BM25/FTS source and `embedding` drives the
    /// cosine source; they are separate inputs so a sentence can be embedded
    /// while analyzed terms drive the lexical side (D2).
    ///
    /// The default implementation degrades honestly: it runs
    /// [`Self::hybrid_search_full`] and reports `matched_by = Text` with no
    /// cosine, because a provider that does not keep per-source pools genuinely
    /// does not know which source matched. Callers must therefore treat
    /// `matched_by` from a default-impl provider as **absent evidence**, not as
    /// a classification — which is why the summary-candidate rules rank
    /// `both`/`text` above `vector`-only rather than trusting the label alone.
    fn hybrid_search_detailed(
        &self,
        label: &str,
        lexical: &acowork_core::retrieval::LexicalQuery<'_>,
        embedding: &[f32],
        k: usize,
        policy: &acowork_core::retrieval::FusionPolicy,
    ) -> Result<Vec<acowork_core::retrieval::FusedHit>> {
        Ok(self
            .hybrid_search_full(
                label,
                lexical.raw,
                embedding,
                k,
                policy.text_weight,
                policy.vector_weight,
                policy.min_cosine,
            )?
            .into_iter()
            .enumerate()
            .map(|(rank, (id, score))| acowork_core::retrieval::FusedHit {
                id,
                matched_by: acowork_core::retrieval::MatchedBy::Text,
                vector_rank: None,
                text_rank: Some(rank),
                cosine: None,
                fused_score: score,
                fused_rank: rank,
            })
            .collect())
    }

    /// Pure text retrieval with label filter. No score threshold: BM25 scores
    /// have no cross-corpus absolute meaning (they drift with corpus size and
    /// average document length), so only their ranking is meaningful.
    fn text_search_with_filter(
        &self,
        label: &str,
        field: &str,
        query_text: &str,
        k: usize,
    ) -> Result<Vec<(u64, f64)>>;

    // ── Phase 1: Node CRUD ──────────────────────────────────────────────

    /// Retrieve all procedural memory nodes.
    fn get_all_procedural_nodes(&self) -> Result<Vec<ProceduralNode>>;

    /// Find procedural nodes matching a trigger condition.
    fn find_procedural_by_trigger(&self, trigger: &str, limit: usize) -> Result<Vec<ProceduralNode>>;

    /// Get a single procedural node by ID.
    fn get_procedural(&self, node_id: u64) -> Result<Option<ProceduralNode>>;

    /// Update a procedural memory node.
    fn update_procedural(&self, node: &ProceduralNode) -> Result<()>;

    /// Find an autobiographical node by its key (e.g., "name", "language").
    fn find_autobiographical_by_key(&self, key: &str) -> Result<Option<AutobiographicalNode>>;

    /// Find autobiographical nodes by category.
    fn find_autobiographical_by_category(
        &self,
        category: AutobioCategory,
    ) -> Result<Vec<AutobiographicalNode>>;

    /// Update an autobiographical memory node.
    fn update_autobiographical(&self, node: &AutobiographicalNode) -> Result<()>;

    // ── Phase 1 C4: Retrieval pipeline support ──────────────────────────

    /// Extract human-readable content from a node by ID.
    ///
    /// This abstracts the property-extraction logic that was previously
    /// in Runtime's `extract_node_content()` helper. Each Provider
    /// implementation decides how to render node content (e.g., combining
    /// `subject + predicate + object` for Knowledge nodes, or
    /// `category: key: value` for Autobiographical nodes).
    ///
    /// Returns `None` if the node does not exist.
    fn get_node_content(&self, node_id: u64) -> Result<Option<String>>;

    /// Get the `session_id` property of a node.
    ///
    /// Used by the retrieval pipeline to filter out nodes belonging to
    /// the current session (prevents re-injecting compaction summaries
    /// that are already in the context window).
    ///
    /// Returns `None` if the node has no `session_id` property or does
    /// not exist.
    fn get_node_session_id(&self, node_id: u64) -> Result<Option<String>>;

    /// Get the lifecycle status of a node.
    ///
    /// Used by the retrieval pipeline to exclude Dormant nodes from final
    /// results (ADR-062 D1) while allowing them to remain as graph-expansion
    /// seeds — Dormant nodes can still bridge to Active nodes via edges.
    ///
    /// Returns `None` if the node does not exist or has no status property.
    fn get_node_status(&self, node_id: u64) -> Result<Option<NodeStatus>>;

    /// Get the creation timestamp of a node.
    ///
    /// Used by the retrieval pipeline to apply time-range filters
    /// (`MemoryFilters.time_range`) — e.g. the `memory_recall` tool's
    /// `since`/`until` parameters ("memories created after X").
    ///
    /// Returns `None` if the node does not exist or has no timestamp.
    fn get_node_created_at(&self, node_id: u64) -> Result<Option<DateTime<Utc>>>;

    /// Push the agent's memory quality configuration to the provider
    /// (ADR-062 D2).
    ///
    /// The provider uses this to parameterize quality thresholds that were
    /// previously hardcoded in the storage engine: dedup thresholds,
    /// consolidation confidence gates, graph-expansion decay, and the
    /// edge-weight formula. Implementations MUST behave identically to the
    /// pre-configuration defaults when this is never called ("zero-config =
    /// current behaviour", ADR-062 §4.2).
    ///
    /// Typically invoked once at provider initialization with the agent's
    /// `MemoryQualityConfig`; the same config is embedded in
    /// `MemoryManagerConfig.quality` for the retrieval side.
    fn apply_quality_config(&self, config: &MemoryQualityConfig) -> Result<()>;

}

