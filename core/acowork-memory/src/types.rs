/// A single conversation episode (user message + assistant response + context).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Episode {
    /// Session identifier.
    pub session_id: String,
    /// Turn index within the session.
    pub turn_index: u32,
    /// Role: "user" | "assistant" | "tool".
    pub role: String,
    /// Content.
    pub content: String,
    /// Semantic embedding vector (generated by Runtime).
    pub embedding: Option<Vec<f32>>,
    /// Timestamp of the interaction.
    pub timestamp: DateTime<Utc>,
    /// Whether this episode has been consolidated to the semantic layer.
    pub consolidated: bool,
    /// Optional contextual metadata (topic, sentiment, etc.).
    pub metadata: HashMap<String, serde_json::Value>,
    /// Importance score assigned by LLM at write time [0.0, 1.0].
    #[serde(default = "default_importance")]
    pub importance: f32,
    /// Optional knowledge classification set by LLM when writing through the
    /// `memory_store` tool (ADR-068). None = pure dialogue fragment (never
    /// promoted). Some = "this episode carries an observation that may be
    /// promoted to the semantic layer by EpisodicDistiller".
    #[serde(default)]
    pub knowledge_subtype: Option<KnowledgeSubType>,
    /// De-contextualised restatement of this episode in one sentence — the
    /// form that stays true once the conversation around it is gone.
    ///
    /// The write-time LLM produces this alongside `content`; it is the
    /// distiller's primary input, because normalisation (what is the durable
    /// claim here?) is a judgement the writing model is already positioned to
    /// make and an offline re-reader is not. `None` on episodes stored before
    /// the field existed, and when the model declined to offer one — the
    /// distiller falls back to `content` in that case.
    #[serde(default)]
    pub normalized: Option<String>,
}

impl Episode {
    /// The durable claim this episode carries — what to consolidate, embed,
    /// and recall on.
    ///
    /// `normalized` when the writing model offered one, otherwise the raw
    /// `content`. Every path that needs "the statement of an episode" goes
    /// through here: the write path embeds it, the distiller projects and
    /// recalls on it. Two copies of that fallback would drift, and a drift
    /// between the vector an episode is stored under and the vector it is
    /// looked up by is exactly the kind of bug that makes consolidation
    /// silently stop matching.
    pub fn statement(&self) -> &str {
        self.normalized
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .unwrap_or(self.content.trim())
    }
}

fn default_importance() -> f32 {
    0.5
}

