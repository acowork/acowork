/**
 * Mobile UI strings — phase 1 scope: boot / connect / login / disconnected /
 * scan / settings / tab bar / offline banner. Chat surfaces keep their
 * existing literals for now and are migrated in later phases; a missing key
 * always falls back to zh-CN, so a half-migrated screen degrades to Chinese
 * instead of rendering a raw key.
 *
 * Language codes deliberately match Desktop's `ProfileTab` options and the
 * server-side `AccountMe.language` field, so an account language can be
 * applied verbatim without a mapping table. The dictionaries are mobile's
 * own: Desktop's locales carry Desktop-only keys, and sharing them would
 * couple two apps that ship on different release cadences.
 */

